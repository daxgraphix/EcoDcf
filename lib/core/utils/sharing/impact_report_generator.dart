import 'dart:io';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:path_provider/path_provider.dart';
import 'package:ecodcf/features/dashboard/domain/entities/dashboard_stats.dart';
import 'package:ecodcf/core/utils/impact_equivalency_converter.dart';
import 'package:intl/intl.dart';

class ImpactReportGenerator {
  static Future<File> generatePdf(DashboardStats stats, String userName) async {
    final pdf = pw.Document();
    final dateStr = DateFormat('MMMM d, yyyy').format(DateTime.now());
    final equivalencies = ImpactEquivalency.getEquivalencies(stats.totalCarbon);

    pdf.addPage(
      pw.Page(
        pageFormat: PdfPageFormat.a4,
        build: (pw.Context context) {
          return pw.Padding(
            padding: const pw.EdgeInsets.all(32),
            child: pw.Column(
              crossAxisAlignment: pw.CrossAxisAlignment.start,
              children: [
                pw.Row(
                  mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
                  children: [
                    pw.Text('EcoDcf Impact Report',
                        style: pw.TextStyle(
                            fontSize: 24, fontWeight: pw.FontWeight.bold, color: PdfColors.green900)),
                    pw.Text(dateStr, style: const pw.TextStyle(color: PdfColors.grey700)),
                  ],
                ),
                pw.SizedBox(height: 40),
                pw.Text('Sustainability Champion:', style: const pw.TextStyle(fontSize: 14, color: PdfColors.grey700)),
                pw.Text(userName, style: pw.TextStyle(fontSize: 20, fontWeight: pw.FontWeight.bold)),
                pw.SizedBox(height: 32),
                pw.Divider(color: PdfColors.green100),
                pw.SizedBox(height: 32),
                pw.Row(
                  mainAxisAlignment: pw.MainAxisAlignment.spaceAround,
                  children: [
                    _buildStat(label: 'Total Carbon', value: '${stats.totalCarbon.toStringAsFixed(1)}kg'),
                    _buildStat(label: 'Carbon Saved', value: '${stats.totalSaved.toStringAsFixed(1)}kg'),
                    _buildStat(label: 'D-Score', value: stats.dscore.toInt().toString()),
                  ],
                ),
                pw.SizedBox(height: 48),
                pw.Text('Real-world Impact Equivalencies',
                    style: pw.TextStyle(fontSize: 18, fontWeight: pw.FontWeight.bold)),
                pw.SizedBox(height: 16),
                pw.TableHelper.fromTextArray(
                  border: null,
                  headerDecoration: const pw.BoxDecoration(color: PdfColors.green50),
                  headerHeight: 30,
                  cellAlignment: pw.Alignment.centerLeft,
                  headerStyle: pw.TextStyle(fontWeight: pw.FontWeight.bold),
                  data: <List<String>>[
                    <String>['Impact Category', 'Equivalent Value'],
                    ...equivalencies.map((e) => [e.label, e.value]),
                  ],
                ),
                pw.Spacer(),
                pw.Align(
                  alignment: pw.Alignment.center,
                  child: pw.Text(
                    'Small digital changes lead to big environmental shifts.',
                    style: pw.TextStyle(fontStyle: pw.FontStyle.italic, color: PdfColors.grey600),
                  ),
                ),
                pw.SizedBox(height: 8),
                pw.Align(
                  alignment: pw.Alignment.center,
                  child: pw.Text('Generated by EcoDcf',
                      style: const pw.TextStyle(fontSize: 10, color: PdfColors.green800)),
                ),
              ],
            ),
          );
        },
      ),
    );

    final output = await getTemporaryDirectory();
    final file = File("${output.path}/EcoDcf_Impact_Report.pdf");
    await file.writeAsBytes(await pdf.save());
    return file;
  }

  static pw.Widget _buildStat({required String label, required String value}) {
    return pw.Column(
      children: [
        pw.Text(value, style: pw.TextStyle(fontSize: 22, fontWeight: pw.FontWeight.bold, color: PdfColors.green700)),
        pw.SizedBox(height: 4),
        pw.Text(label, style: const pw.TextStyle(fontSize: 12, color: PdfColors.grey600)),
      ],
    );
  }
}
